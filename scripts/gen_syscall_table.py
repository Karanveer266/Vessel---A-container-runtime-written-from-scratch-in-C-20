"""Generate src/runtime/syscall_table.inc from kernel UAPI headers.

Usage: gen_syscall_table.py <unistd_64.h (x86_64)> <asm-generic/unistd.h> > syscall_table.inc

The output is checked in. Regenerate when adding support for newer syscalls.
x86_64 numbers come from arch/x86 (unistd_64.h); aarch64 uses the generic
table (asm-generic/unistd.h) with the 64-bit names of the __NR3264_* aliases.
"""
import re
import sys


def parse_x86(path):
    table = {}
    for line in open(path, encoding="utf-8"):
        m = re.match(r"#define __NR_(\w+)\s+(\d+)\s*$", line)
        if m:
            table.setdefault(int(m.group(2)), m.group(1))
    return table


def parse_generic(path):
    table = {}
    skip_depth = 0
    for line in open(path, encoding="utf-8"):
        s = line.strip()
        # Drop the 32-bit-only time syscalls block; aarch64 is 64-bit only.
        if s.startswith("#if") and ("__BITS_PER_LONG == 32" in s or "__SYSCALL_COMPAT" in s
                                     or "__ARCH_WANT_TIME32_SYSCALLS" in s and "!=" not in s):
            skip_depth += 1
            continue
        if skip_depth:
            if s.startswith("#if"):
                skip_depth += 1
            elif s.startswith("#endif"):
                skip_depth -= 1
            continue
        m = re.match(r"#define __NR(3264)?_(\w+)\s+(\d+)\s*$", s)
        if m and m.group(2) not in ("syscalls", "arch_specific_syscall"):
            table.setdefault(int(m.group(3)), m.group(2))
    return table


def emit(name, table):
    print(f"static constexpr SyscallEntry {name}[] = {{")
    for nr in sorted(table):
        print(f'    {{{nr}, "{table[nr]}"}},')
    print("};")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    print("// GENERATED by scripts/gen_syscall_table.py — do not edit.")
    print("// clang-format off")
    print("#if defined(__x86_64__)")
    emit("kSyscalls", parse_x86(sys.argv[1]))
    print("#elif defined(__aarch64__)")
    emit("kSyscalls", parse_generic(sys.argv[2]))
    print("#else")
    print('#error "vessel: unsupported architecture (x86_64 and aarch64 only)"')
    print("#endif")


if __name__ == "__main__":
    main()
